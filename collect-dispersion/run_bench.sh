#!/bin/bash

# Проверяем, что переданы оба аргумента
if [ "$#" -ne 2 ]; then
    echo "Использование: $0 <TYPE> <SIZE>"
    echo "Пример: $0 SUM 120"
    exit 1
fi

TYPE=$1
SIZE=$2
EVENTS="LLC-loads,LLC-load-misses,LLC-stores,LLC-store-misses"

echo "=========================================================="
echo "Запуск серии тестов для типа: $TYPE, размер: $SIZE"
echo "=========================================================="
echo ""

# Цикл по количеству ядер от 1 до 4
for CORES in {1..4}
do
    echo "----------------------------------------------------------"
    echo "Шаг: Запуск на $CORES ядр(ах/е)..."
    echo "----------------------------------------------------------"
    
    perf stat -e "$EVENTS" ./a.out --type "$TYPE" --size "$SIZE" --cores "$CORES"
    
    echo ""
    # Небольшая пауза в 1 секунду, чтобы система успела сбросить кэши и остыть
    sleep 1 
done

echo "=========================================================="
echo "Тестирование для $TYPE ($SIZE) завершено!"
echo "=========================================================="
