#!/bin/bash

# Проверяем, что переданы аргументы
if [ "$#" -lt 2 ]; then
    echo "Использование: $0 <TYPE1> <SIZE1> <SIZE2>... <TYPE2> <SIZE1>..."
    echo "Пример: $0 SUM 60 84 MUL 600 660 720"
    exit 1
fi

# Создаем папку для результатов, если её нет
OUTPUT_DIR="output"
mkdir -p "$OUTPUT_DIR"

CURRENT_TYPE=""

echo "=========================================================="
echo "ЗАПУСК ПАКЕТНОГО МУЛЬТИ-ТЕСТИРОВАНИЯ"
echo "=========================================================="

# Итерируемся по всем переданным аргументам
for ARG in "$@"
do
    # Проверяем, является ли аргумент числом
    if [[ "$ARG" =~ ^[0-9]+$ ]]; then
        # Если это число, но тип еще не был задан — это ошибка использования
        if [ -z "$CURRENT_TYPE" ]; then
            echo "Ошибка: Указан размер $ARG, но не задан тип процедуры перед ним!"
            exit 1
        fi
        
        # Если все ок, работаем с текущим размером
        SIZE=$ARG
        TARGET_FILE="${OUTPUT_DIR}/${CURRENT_TYPE}_${SIZE}.txt"
        
        echo ">>> Запускаю: тип $CURRENT_TYPE, размер $SIZE"
        echo "    Лог пишется в: $TARGET_FILE"
        
        # Перенаправляем весь вывод (и stdout, и stderr) в отдельный файл
        {
            echo "=========================================================="
            echo "Запуск серии тестов для типа: $CURRENT_TYPE, размер: $SIZE"
            echo "Дата запуска: $(date)"
            echo "=========================================================="
            echo ""
            
            # Вызываем ручной или автоматический замер (что у вас сейчас используется)
            ./run_bench.sh "$CURRENT_TYPE" "$SIZE"
            
            echo ""
            echo "Тестирование для $CURRENT_TYPE ($SIZE) завершено!"
        } > "$TARGET_FILE" 2>&1
        
        # Небольшая пауза, чтобы остудить ядра
        sleep 3
    else
        # Если аргумент — не число, значит это имя новой процедуры (SUM, MUL, COPY и т.д.)
        CURRENT_TYPE=$ARG
        echo "----------------------------------------------------------"
        echo "Переключаю тип тестирования на: $CURRENT_TYPE"
        echo "----------------------------------------------------------"
    fi
done

echo ""
echo "=========================================================="
echo "ПАКЕТНОЕ ТЕСТИРОВАНИЕ ВСЕХ ТИПОВ УСПЕШНО ЗАВЕРШЕНО!"
echo "Результаты сохранены в папке './$OUTPUT_DIR/'"
echo "=========================================================="
